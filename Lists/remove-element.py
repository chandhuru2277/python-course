# list concat
foods= ["egg salad", "soup","fried bread", "chicken 65", "pizza"]
print(foods)
# remove the element
foods.remove("soup")
print(foods)
# pop the element in end
foods.pop()
print(foods)
# pop the element with index
foods.pop(1)
print(foods)
# clear the all element
foods.clear()
print(foods)